namespace IPasswrd.Core;

/// <summary>
/// Перенос в запись, собранную формой, всего того, чего форма не показывает.
///
/// Форма редактирования на Windows строит запись с нуля: берёт значения полей и складывает новый
/// VaultItem. Для полей это правильно — так очищенная строка означает «удалить», а не «оставить
/// как было». Но всё, чего в форме нет, при этом молча исчезало: приложенные фотографии,
/// звёздочка избранного и поля, записанные более новой версией программы. Человек правил
/// название карты, а терял скан паспорта — и узнавал об этом через месяц, когда скан
/// понадобился.
///
/// Почему это не спрятано внутрь <see cref="Vault.Update"/>: Update честно кладёт то, что дали, и
/// на этом стоит удаление вложений. Убрал последнее вложение — значит его нет, а не «верните
/// обратно». Переносить нужно ровно там, где запись пересобирают с нуля, а не везде.
///
/// История паролей сюда не входит: её ведёт сам сейф в Update, потому что она меняется от факта
/// сохранения, а не от того, что показала форма.
/// </summary>
public static class FormEdit
{
    /// <summary>
    /// Дополняет <paramref name="next"/> тем, чего форма не касалась, и возвращает его же.
    ///
    /// Переносится безусловно: перечисленного ниже нет ни в одной форме, поэтому «пусто» в
    /// собранной записи всегда означает «форма про это не знает», а не «человек убрал».
    /// Когда в форме появится собственный список вложений (на телефоне он уже есть), их надо
    /// будет убрать отсюда — иначе удалённое последним вложение вернётся при сохранении.
    /// </summary>
    public static VaultItem Carry(VaultItem? previous, VaultItem next)
    {
        if (previous is null) return next;

        next.Attachments = new List<Attachment>(previous.Attachments);
        next.Favorite = previous.Favorite;
        next.Extra = previous.Extra;

        return next;
    }
}
